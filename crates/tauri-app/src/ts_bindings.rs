//! N-11.7: the TypeScript types in `frontend/types/generated.ts` are generated
//! from the Rust types via ts-rs. This test fails when the checked-in file
//! drifts from the Rust sources. Regenerate it with:
//!
//!     UPDATE_TS_BINDINGS=1 cargo test -p nisaba-tauri ts_bindings

use std::path::PathBuf;

use ts_rs::TS;

fn generated_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../frontend/types/generated.ts")
}

fn config() -> ts_rs::Config {
    // The frontend treats all integers as `number` (matching the previous
    // hand-written types); values come over the wire as JSON numbers.
    ts_rs::Config::new().with_large_int("number")
}

fn render<T: TS + 'static>() -> String {
    let s = T::export_to_string(&config()).expect("ts-rs export failed");
    // All types land in one file, so drop the per-file cross imports ts-rs
    // emits (e.g. SyncEngineEvent's `import type { Platform } from "./Platform"`).
    let mut out: String = s
        .lines()
        .filter(|l| !(l.starts_with("import ") && l.contains("./")))
        .collect::<Vec<_>>()
        .join("\n");
    out.push('\n');
    out
}

fn build_bindings() -> String {
    let mut out = String::from(
        "// AUTO-GENERATED by ts-rs — do not edit by hand.\n\
         // Regenerate: UPDATE_TS_BINDINGS=1 cargo test -p nisaba-tauri ts_bindings\n\
         // Sources:\n\
         //   Platform, ProductVariant — crates/core/src/types.rs\n\
         //   SyncEngineEvent          — crates/core/src/sync_engine.rs\n\
         //   MergeSummary             — crates/p2p/src/types.rs\n\
         //   SyncStatusPayload        — crates/tauri-app/src/commands/sync.rs\n\
         \n",
    );
    for section in [
        render::<nisaba_core::types::Platform>(),
        render::<nisaba_core::types::ProductVariant>(),
        render::<nisaba_core::sync_engine::SyncEngineEvent>(),
        render::<nisaba_p2p::types::MergeSummary>(),
        render::<crate::commands::sync::SyncStatusPayload>(),
    ] {
        out.push_str(&section);
        out.push('\n');
    }
    out
}

#[test]
fn ts_bindings_are_current() {
    let expected = build_bindings();
    let path = generated_path();
    if std::env::var("UPDATE_TS_BINDINGS").is_ok() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).expect("failed to create types dir");
        }
        std::fs::write(&path, &expected).expect("failed to write generated.ts");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!(
            "frontend/types/generated.ts is missing — run with UPDATE_TS_BINDINGS=1: {}",
            path.display()
        )
    });
    assert_eq!(
        current, expected,
        "TypeScript bindings drifted from the Rust types.\n\
         Regenerate: UPDATE_TS_BINDINGS=1 cargo test -p nisaba-tauri ts_bindings"
    );
}
